const placeholders = (value) => (value.match(/\{\w+\}/g) ?? []).sort().join(",");
for (const [locale, values] of Object.entries(rows)) {
  if (values.length !== keys.length) throw new Error(`Institution translations incomplete for ${locale}`);
  const pack = {};
  for (const [index, key] of keys.entries()) {
    const value = values[index];
    if (typeof value !== "string" || !value.trim()) throw new Error(`Institution translation empty: ${locale}.${key}`);
    if (placeholders(value) !== placeholders(rows.en[index])) throw new Error(`Institution translation placeholders differ: ${locale}.${key}`);
    pack[key] = value;
  }
  translations[locale] = pack;
}
function message(locale, key, values = {}) {
  const text = Object.hasOwn(translations, locale) && Object.hasOwn(translations[locale], key)
    ? translations[locale][key]
    : key;
  return text.replace(/\{(\w+)\}/g, (token, name) => values[name] ?? token);
}
function coverage(locale) {
  const pack = Object.hasOwn(translations, locale) ? translations[locale] : {};
  const missing = keys.filter((key) => !Object.hasOwn(pack, key) || typeof pack[key] !== "string" || !pack[key].trim());
  return { total: keys.length, translated: keys.length - missing.length, missing };
}
