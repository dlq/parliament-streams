"""Compare official public collector endpoints from hosted and local networks."""

from __future__ import annotations

import hashlib
import json
import platform
import socket
import ssl
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode, urlsplit
from urllib.request import Request, urlopen
from zoneinfo import ZoneInfo

AGENT = "parliament-streams-schedule-collector/0.1 (+https://github.com/dlq/parliament-streams)"
ROOT = "https://www.parliamentarytv.org.tw/"
HEADERS = ["Server", "Content-Type", "Via", "X-Cache", "CF-Mitigated", "X-Amz-Cf-Pop", "X-Iinfo"]
LIMIT = 65536


def summarize(body: bytes, headers: dict[str, str]) -> dict:
    text = body.decode("utf-8", errors="replace")
    result = {
        "sample_sha256": hashlib.sha256(body).hexdigest(),
        "sample_bytes": len(body),
        "headers": headers,
        "markers": [
            marker
            for marker in (
                "Request blocked",
                "The request could not be satisfied",
                "Generated by cloudfront",
                "Access Denied",
                "Access denied",
                "Cloudflare",
                "Incapsula",
                "Imperva",
                "Akamai",
                "geo restriction",
                "country",
                "unusual traffic",
                "captcha",
            )
            if marker.lower() in text.lower()
        ],
    }
    try:
        data = json.loads(text)
        result["json_type"] = type(data).__name__
        if isinstance(data, list):
            result["rows"] = len(data)
    except ValueError:
        result["ical"] = text.startswith("BEGIN:VCALENDAR")
    return result


def probe(name: str, url: str, extra: dict) -> dict:
    result = {"name": name, "url": url}
    try:
        request = Request(
            url, headers={"User-Agent": AGENT, "Accept": "text/html, application/json", **extra}
        )
        try:
            response = urlopen(request, timeout=20)
        except HTTPError as error:
            response = error
        with response:
            result.update(status=response.status, final_url=response.url)
            result.update(
                summarize(
                    response.read(LIMIT),
                    {k: response.headers[k] for k in HEADERS if k in response.headers},
                )
            )
    except (URLError, TimeoutError, ssl.SSLError, OSError) as error:
        result["error_type"] = type(error).__name__
    return result


def main() -> None:
    day = datetime.now(ZoneInfo("Asia/Taipei")).strftime("%Y/%m/%d")
    api = ROOT + "api/get_program.php?" + urlencode({"ch": "ly1", "date": day})
    ajax = {
        "Accept": "application/json, text/javascript, */*; q=0.01",
        "Referer": ROOT,
        "X-Requested-With": "XMLHttpRequest",
    }
    ny = "https://www.nysenate.gov/session/calendar-download"
    cases = [
        ("taiwan-home", ROOT, {}),
        ("taiwan-script", ROOT + "js/ww_index.js?T=20250204", {}),
        ("taiwan-collector", api, {}),
        ("taiwan-ajax", api, ajax),
        ("new-york-home", "https://www.nysenate.gov/", {}),
        ("new-york-events", "https://www.nysenate.gov/events", {}),
        ("new-york-collector", ny, {}),
        (
            "new-york-calendar-headers",
            ny,
            {"Accept": "text/calendar", "Referer": "https://www.nysenate.gov/events"},
        ),
    ]
    results = []
    for name, url, headers in cases:
        result = probe(name, url, headers)
        results.append(result)
        print(json.dumps(result), flush=True)
    for name, url in [("taiwan", api), ("new-york", ny)]:
        for transport in ["--http1.1", "--http2"]:
            response = subprocess.run(
                [
                    "curl",
                    "--silent",
                    "--show-error",
                    "--max-time",
                    "20",
                    "--max-filesize",
                    str(LIMIT),
                    "--ipv4",
                    transport,
                    "--user-agent",
                    AGENT,
                    "--header",
                    "Accept: text/html, application/json",
                    "--write-out",
                    "\n%{json}",
                    url,
                ],
                capture_output=True,
                check=False,
            )
            body, _, metadata = response.stdout.rpartition(b"\n")
            record = {"name": name + "-curl-" + transport[2:], "exit_code": response.returncode}
            try:
                info = json.loads(metadata)
                record["transport"] = {
                    key: info.get(key)
                    for key in (
                        "http_code",
                        "http_version",
                        "remote_ip",
                        "ssl_verify_result",
                        "num_redirects",
                    )
                }
                record.update(summarize(body, {}))
            except ValueError:
                record["metadata_missing"] = True
            results.append(record)
            print(json.dumps(record), flush=True)
    dns = {}
    for host in {urlsplit(url).hostname for _, url, _ in cases}:
        try:
            dns[host] = sorted(
                {item[4][0] for item in socket.getaddrinfo(host, 443, type=socket.SOCK_STREAM)}
            )
        except OSError:
            dns[host] = []
    report = {
        "checked_at": datetime.now(UTC).isoformat(),
        "platform": platform.system(),
        "python": platform.python_version(),
        "ssl": ssl.OPENSSL_VERSION,
        "dns": dns,
        "results": results,
    }
    Path("collector-access-diagnostic.json").write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
